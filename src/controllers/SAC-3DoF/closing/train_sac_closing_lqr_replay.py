def make_closing_env(mode, seed, reward_version, monitor=False):
    """Construct either the single-reward or versioned Gym API safely."""

    kwargs = {
        "phase": "closing",
        "mode": mode,
        "dt": 1.0,
        "max_time": None,
        "integrator": "rk4",
        "normalize_action": True,
        "seed": seed,
    }
    parameters = inspect.signature(Docking3DoFGymEnv.__init__).parameters
    if "closing_reward_version" in parameters:
        kwargs["closing_reward_version"] = reward_version
    elif reward_version != "v15":
        raise ValueError(
            "The current Gym environment exposes one closing reward only; "
            "the dataset and training reward must be 'v15'."
        )
    env = Docking3DoFGymEnv(**kwargs)
    return Monitor(env) if monitor else env


def parse_args():
    parser = argparse.ArgumentParser(
        description=(
            "Train standalone SAC on complete closing episodes after "
            "prefilling replay with successful LQR demonstrations."
        )
    )
    parser.add_argument(
        "--demonstrations",
        type=Path,
        required=True,
        help="SAC-format LQR demonstration NPZ generated by the companion script.",
    )
    parser.add_argument("--seeds", type=int, nargs="+", default=[0])
    parser.add_argument("--total-timesteps", type=int, default=600_000)
    parser.add_argument(
        "--reward-version",
        default=None,
        help=(
            "Closing reward version. By default it is read from the dataset; "
            "an explicit value must match the dataset."
        ),
    )
    parser.add_argument(
        "--buffer-size",
        type=int,
        default=None,
        help=(
            "Replay capacity. By default: demonstrations + online steps + "
            "--buffer-margin, rounded up to the next 100k."
        ),
    )
    parser.add_argument("--buffer-margin", type=int, default=50_000)
    parser.add_argument(
        "--checkpoint-steps",
        type=int,
        nargs="+",
        default=None,
    )
    parser.add_argument(
        "--validation-seeds",
        type=int,
        nargs="+",
        default=DEFAULT_VALIDATION_SEEDS,
    )
    parser.add_argument("--max-eval-steps", type=int, default=12_000)
    parser.add_argument(
        "--device",
        choices=["auto", "cpu", "cuda"],
        default="auto",
    )
    parser.add_argument("--experiment-name", default=None)
    parser.add_argument("--progress-bar", action="store_true")
    parser.add_argument("--overwrite", action="store_true")
    parser.add_argument(
        "--no-initialize-normalization",
        action="store_true",
        help="Do not initialize VecNormalize statistics from demonstrations.",
    )
    args = parser.parse_args()

    if args.total_timesteps <= 0:
        parser.error("--total-timesteps must be positive.")
    if args.buffer_margin < 0:
        parser.error("--buffer-margin must be non-negative.")
    if args.buffer_size is not None and args.buffer_size <= 0:
        parser.error("--buffer-size must be positive.")
    if args.max_eval_steps <= 0:
        parser.error("--max-eval-steps must be positive.")
    if not args.seeds or len(set(args.seeds)) != len(args.seeds):
        parser.error("--seeds must contain unique values.")
    if not args.validation_seeds:
        parser.error("At least one --validation-seeds value is required.")
    if len(set(args.validation_seeds)) != len(args.validation_seeds):
        parser.error("--validation-seeds must contain unique values.")
    if set(args.seeds) & set(args.validation_seeds):
        parser.error("Training and validation seeds must be disjoint.")
    if args.device == "cuda" and not torch.cuda.is_available():
        parser.error("CUDA was requested but torch.cuda.is_available() is false.")
    return args


def resolve_checkpoint_steps(requested_steps, total_timesteps):
    if requested_steps is None:
        requested_steps = list(range(100_000, total_timesteps + 1, 100_000))
        if not requested_steps or requested_steps[-1] != total_timesteps:
            requested_steps.append(total_timesteps)
    checkpoints = sorted(set(int(value) for value in requested_steps))
    if not checkpoints:
        raise ValueError("At least one checkpoint is required.")
    if checkpoints[0] <= 0 or checkpoints[-1] > total_timesteps:
        raise ValueError("Checkpoints must lie in [1, total_timesteps].")
    return checkpoints


def resolve_buffer_size(
    requested_size,
    demonstration_count,
    total_timesteps,
    buffer_margin,
):
    required_size = demonstration_count + total_timesteps + buffer_margin
    if requested_size is None:
        rounding = 100_000
        return int(np.ceil(required_size / rounding) * rounding)
    if requested_size < demonstration_count:
        raise ValueError(
            "Replay buffer cannot hold the demonstration dataset: "
            f"{requested_size} < {demonstration_count}."
        )
    if requested_size < demonstration_count + total_timesteps:
        raise ValueError(
            "Replay buffer would overwrite demonstrations before training ends: "
            f"{requested_size} < {demonstration_count + total_timesteps}. "
            "Increase --buffer-size or omit it for automatic sizing."
        )
    return int(requested_size)


def initialize_vecnormalize_from_demonstrations(
    vecnormalize,
    dataset,
    gamma,
    chunk_size=100_000,
):
    """Initialize observation and return statistics without normalizing replay."""

    observations = np.asarray(dataset["observations"], dtype=np.float64)
    next_observations = np.asarray(
        dataset["next_observations"],
        dtype=np.float64,
    )
    rewards = np.asarray(dataset["rewards"], dtype=np.float64)
    episode_offsets = np.asarray(dataset["episode_offsets"], dtype=np.int64)

    for start in range(0, len(observations), chunk_size):
        vecnormalize.obs_rms.update(observations[start : start + chunk_size])

    # Observations already contain every pre-action state. Add only the final
    # next state of each episode to represent the complete observed sequence.
    terminal_indices = episode_offsets[1:] - 1
    vecnormalize.obs_rms.update(next_observations[terminal_indices])

    discounted_returns = np.empty_like(rewards, dtype=np.float64)
    for episode_index in range(len(episode_offsets) - 1):
        start = int(episode_offsets[episode_index])
        end = int(episode_offsets[episode_index + 1])
        running_return = 0.0
        for index in range(start, end):
            running_return = float(gamma) * running_return + rewards[index]
            discounted_returns[index] = running_return
    for start in range(0, len(discounted_returns), chunk_size):
        vecnormalize.ret_rms.update(
            discounted_returns[start : start + chunk_size]
        )


def prefill_replay_buffer(model, dataset, progress_every=50_000):
    """Insert raw one-step demonstration transitions into an empty SB3 buffer."""

    replay_buffer = model.replay_buffer
    if replay_buffer is None:
        raise RuntimeError("SAC replay buffer has not been initialized.")
    if replay_buffer.size() != 0:
        raise ValueError("Replay prefill requires an empty replay buffer.")
    if getattr(replay_buffer, "n_envs", None) != 1:
        raise ValueError("Demonstration prefill currently requires one environment.")

    observations = np.asarray(dataset["observations"], dtype=np.float32)
    actions = np.asarray(dataset["actions"], dtype=np.float32)
    rewards = np.asarray(dataset["rewards"], dtype=np.float32)
    next_observations = np.asarray(
        dataset["next_observations"],
        dtype=np.float32,
    )
    terminated = np.asarray(dataset["terminated"], dtype=np.bool_)
    truncated = np.asarray(dataset["truncated"], dtype=np.bool_)
    transition_count = len(rewards)

    if replay_buffer.buffer_size < transition_count:
        raise ValueError(
            "Replay buffer is smaller than the demonstration dataset: "
            f"{replay_buffer.buffer_size} < {transition_count}."
        )

    for index in range(transition_count):
        is_terminated = bool(terminated[index])
        is_truncated = bool(truncated[index])
        replay_buffer.add(
            observations[index][None, :],
            next_observations[index][None, :],
            actions[index][None, :],
            np.asarray([rewards[index]], dtype=np.float32),
            np.asarray([is_terminated or is_truncated], dtype=np.float32),
            [
                {
                    "TimeLimit.truncated": bool(
                        is_truncated and not is_terminated
                    )
                }
            ],
        )
        completed = index + 1
        if progress_every and (
            completed % progress_every == 0 or completed == transition_count
        ):
            print(
                f"Prefilled {completed:,}/{transition_count:,} "
                "LQR transitions"
            )

    if replay_buffer.size() != transition_count:
        raise RuntimeError(
            "Replay prefill size mismatch: "
            f"{replay_buffer.size()} != {transition_count}."
        )
    return transition_count


def safe_output_paths(experiment_name, seed, overwrite):
    model_dir = MODEL_ROOT / experiment_name / f"seed_{seed}"
    result_dir = RESULTS_ROOT / experiment_name / f"seed_{seed}"
    protected_outputs = (
        model_dir / "final_model.zip",
        result_dir / "checkpoint_metrics.csv",
        result_dir / "replay_prefill.json",
    )
    existing = [path for path in protected_outputs if path.exists()]
    if existing and not overwrite:
        raise FileExistsError(
            "Experiment output already exists. Choose a new --experiment-name "
            f"or pass --overwrite: {existing}"
        )
    model_dir.mkdir(parents=True, exist_ok=True)
    result_dir.mkdir(parents=True, exist_ok=True)
    return model_dir, result_dir


def write_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as file:
        json.dump(value, file, indent=2, sort_keys=True)


def evaluate_full_closing_policy(
    model,
    vecnormalize,
    seeds,
    max_steps,
    reward_version,
):
    """Evaluate deterministically on raw full-closing testing episodes."""

    results = []
    for seed in seeds:
        env = make_closing_env(
            mode="testing",
            seed=seed,
            reward_version=reward_version,
            monitor=False,
        )
        try:
            observation, _ = env.reset(seed=seed)
            episode_return = 0.0
            terminated = False
            truncated = False
            info = {}
            steps = 0
            while not (terminated or truncated) and steps < max_steps:
                normalized_observation = vecnormalize.normalize_obs(
                    observation.reshape(1, -1)
                )
                action, _ = model.predict(
                    normalized_observation,
                    deterministic=True,
                )
                observation, reward, terminated, truncated, info = env.step(
                    np.asarray(action[0], dtype=np.float32)
                )
                episode_return += float(reward)
                steps += 1

            target_error = env.core_env.state - env.core_env.p3_target
            target_error = np.asarray(target_error, dtype=np.float64)
            target_error[4] = env.core_env.wrap_to_pi(target_error[4])
            tolerance = np.asarray(
                env.core_env.p3_target_tolerance,
                dtype=np.float64,
            )
            results.append(
                {
                    "seed": int(seed),
                    "episode_return": float(episode_return),
                    "steps": int(steps),
                    "success": bool(info.get("success", False)),
                    "failure": bool(info.get("failure", False)),
                    "timeout": bool(
                        info.get("time_limit", False)
                        or (steps >= max_steps and not terminated)
                    ),
                    "termination_reason": info.get("termination_reason"),
                    "final_max_target_ratio": float(
                        np.max(np.abs(target_error) / tolerance)
                    ),
                }
            )
        finally:
            env.close()
    return results


def summarize_evaluation(results):
    count = len(results)
    returns = np.asarray(
        [result["episode_return"] for result in results],
        dtype=np.float64,
    )
    return {
        "mean_return": float(np.mean(returns)),
        "std_return": float(np.std(returns)),
        "success_rate": float(
            sum(result["success"] for result in results) / count
        ),
        "failure_rate": float(
            sum(result["failure"] for result in results) / count
        ),
        "time_limit_rate": float(
            sum(result["timeout"] for result in results) / count
        ),
        "mean_steps": float(
            np.mean([result["steps"] for result in results])
        ),
        "mean_final_max_target_ratio": float(
            np.mean(
                [result["final_max_target_ratio"] for result in results]
            )
        ),
    }


class FullClosingCheckpointCallback(BaseCallback):
    """Save and evaluate exact online-timestep checkpoints."""

    def __init__(
        self,
        training_seed,
        checkpoint_steps,
        validation_seeds,
        max_eval_steps,
        reward_version,
        model_dir,
        result_dir,
    ):
        super().__init__()
        self.training_seed = int(training_seed)
        self.checkpoint_steps = list(checkpoint_steps)
        self.validation_seeds = list(validation_seeds)
        self.max_eval_steps = int(max_eval_steps)
        self.reward_version = reward_version
        self.model_dir = Path(model_dir)
        self.result_dir = Path(result_dir)
        self.next_checkpoint_index = 0
        self.completed_episodes = 0
        self.rows = []
        self.rollout_rows = []
        self.best_mean_return = -np.inf
        self.best_checkpoint = None
        self.best_checkpoint_episode = None

    def _on_step(self):
        for info in self.locals.get("infos", []):
            if info.get("episode") is not None:
                self.completed_episodes += 1
        while self.next_checkpoint_index < len(self.checkpoint_steps):
            checkpoint = self.checkpoint_steps[self.next_checkpoint_index]
            if self.num_timesteps < checkpoint:
                break
            self._evaluate_and_save(checkpoint)
            self.next_checkpoint_index += 1
        return True

    def _evaluate_and_save(self, checkpoint):
        vecnormalize = self.model.get_vec_normalize_env()
        if vecnormalize is None:
            raise RuntimeError("VecNormalize is required for evaluation.")
        stem = f"model_{checkpoint:07d}_steps"
        self.model.save(self.model_dir / stem)
        vecnormalize.save(self.model_dir / f"{stem}_vecnormalize.pkl")

        results = evaluate_full_closing_policy(
            model=self.model,
            vecnormalize=vecnormalize,
            seeds=self.validation_seeds,
            max_steps=self.max_eval_steps,
            reward_version=self.reward_version,
        )
        summary = summarize_evaluation(results)
        row = {
            "training_seed": self.training_seed,
            "checkpoint": int(checkpoint),
            "episode": self.completed_episodes,
            **summary,
        }
        self.rows.append(row)
        self.rollout_rows.extend(
            {
                "training_seed": self.training_seed,
                "checkpoint": int(checkpoint),
                **result,
            }
            for result in results
        )
        self._write_csv(
            self.result_dir / "checkpoint_metrics.csv",
            self.rows,
        )
        self._write_csv(
            self.result_dir / "validation_rollout_metrics.csv",
            self.rollout_rows,
        )

        if summary["mean_return"] > self.best_mean_return:
            self.best_mean_return = summary["mean_return"]
            self.best_checkpoint = int(checkpoint)
            self.best_checkpoint_episode = self.completed_episodes
            self.model.save(self.model_dir / "best_model")
            vecnormalize.save(self.model_dir / "best_vecnormalize.pkl")
            write_json(
                self.result_dir / "best_checkpoint.json",
                row,
            )
        print(
            f"Checkpoint {checkpoint:,} | "
            f"mean return={summary['mean_return']:.3f} | "
            f"success={summary['success_rate']:.3f} | "
            f"failure={summary['failure_rate']:.3f} | "
            f"timeout={summary['time_limit_rate']:.3f}"
        )

    @staticmethod
    def _write_csv(path, rows):
        if not rows:
            return
        with Path(path).open("w", newline="", encoding="utf-8") as file:
            writer = csv.DictWriter(file, fieldnames=list(rows[0]))
            writer.writeheader()
            writer.writerows(rows)

    def get_best_checkpoint(self):
        return (
            self.best_checkpoint,
            self.best_mean_return,
            self.best_checkpoint_episode,
        )


def train_one_seed(
    args,
    dataset,
    dataset_metadata,
    reward_version,
    buffer_size,
    checkpoint_steps,
    experiment_name,
    seed,
):
    model_dir, result_dir = safe_output_paths(
        experiment_name,
        seed,
        args.overwrite,
    )
    train_env = None
    model = None
    try:
        train_env = DummyVecEnv(
            [
                lambda seed=seed: make_closing_env(
                    mode="training",
                    seed=seed,
                    reward_version=reward_version,
                    monitor=True,
                )
            ]
        )
        train_env = VecNormalize(
            train_env,
            norm_obs=True,
            norm_reward=True,
            clip_obs=10.0,
            clip_reward=10.0,
            gamma=TRIAL_16_PARAMS["gamma"],
        )
        if not args.no_initialize_normalization:
            initialize_vecnormalize_from_demonstrations(
                train_env,
                dataset,
                gamma=TRIAL_16_PARAMS["gamma"],
            )

        model = SAC(
            policy="MlpPolicy",
            env=train_env,
            learning_rate=TRIAL_16_PARAMS["learning_rate"],
            buffer_size=buffer_size,
            learning_starts=0,
            batch_size=TRIAL_16_PARAMS["batch_size"],
            tau=TRIAL_16_PARAMS["tau"],
            gamma=TRIAL_16_PARAMS["gamma"],
            train_freq=TRIAL_16_PARAMS["train_freq"],
            gradient_steps=TRIAL_16_PARAMS["gradient_steps"],
            ent_coef=TRIAL_16_PARAMS["ent_coef"],
            target_update_interval=1,
            verbose=1,
            seed=seed,
            tensorboard_log=str(LOG_ROOT / experiment_name),
            device=args.device,
        )
        prefilled_count = prefill_replay_buffer(model, dataset)
        write_json(
            result_dir / "replay_prefill.json",
            {
                "dataset_path": str(args.demonstrations.resolve()),
                "dataset_metadata": dataset_metadata,
                "prefilled_transitions": prefilled_count,
                "replay_capacity": buffer_size,
                "learning_starts": 0,
                "vecnormalize_initialized_from_demonstrations": (
                    not args.no_initialize_normalization
                ),
            },
        )

        checkpoint_callback = FullClosingCheckpointCallback(
            training_seed=seed,
            checkpoint_steps=checkpoint_steps,
            validation_seeds=args.validation_seeds,
            max_eval_steps=args.max_eval_steps,
            reward_version=reward_version,
            model_dir=model_dir,
            result_dir=result_dir,
        )
        training_return_callback = TrainingReturnCallback(
            training_seed=seed,
            result_dir=str(result_dir),
            model_name=f"{experiment_name} - seed {seed}",
        )

        model.learn(
            total_timesteps=args.total_timesteps,
            tb_log_name=f"{experiment_name}_seed_{seed}",
            progress_bar=args.progress_bar,
            callback=[training_return_callback, checkpoint_callback],
        )
        model.save(model_dir / "final_model")
        train_env.save(model_dir / "final_vecnormalize.pkl")

        best_checkpoint, _, best_checkpoint_episode = (
            checkpoint_callback.get_best_checkpoint()
        )
        training_return_callback.set_best_checkpoint(
            best_checkpoint_episode,
            best_checkpoint,
        )
        training_return_callback.save_outputs()
    finally:
        if train_env is not None:
            train_env.close()
        del model
        gc.collect()
        if torch.cuda.is_available():
            torch.cuda.empty_cache()


def main():
    args = parse_args()
    dataset, dataset_metadata = load_demonstration_dataset(args.demonstrations)
    dataset_reward_version = dataset_metadata["reward_version"]
    reward_version = args.reward_version or dataset_reward_version
    if reward_version != dataset_reward_version:
        raise ValueError(
            "Training reward version must match the demonstration dataset: "
            f"{reward_version!r} != {dataset_reward_version!r}."
        )

    demonstration_count = int(dataset_metadata["transition_count"])
    buffer_size = resolve_buffer_size(
        args.buffer_size,
        demonstration_count,
        args.total_timesteps,
        args.buffer_margin,
    )
    checkpoint_steps = resolve_checkpoint_steps(
        args.checkpoint_steps,
        args.total_timesteps,
    )
    if args.experiment_name is None:
        experiment_name = (
            f"sac_closing_reward{reward_version}_lqr_replay_"
            f"{args.total_timesteps}steps"
        )
    else:
        experiment_name = args.experiment_name

    experiment_config = {
        "experiment_name": experiment_name,
        "demonstration_dataset": str(args.demonstrations.resolve()),
        "demonstration_metadata": dataset_metadata,
        "training_seeds": args.seeds,
        "validation_seeds": args.validation_seeds,
        "total_timesteps": args.total_timesteps,
        "reward_version": reward_version,
        "checkpoint_steps": checkpoint_steps,
        "max_eval_steps": args.max_eval_steps,
        "buffer_size": buffer_size,
        "buffer_margin": args.buffer_margin,
        "learning_starts": 0,
        "full_p2_resets_only": True,
        "lqr_used_during_online_training": False,
        "trial_16_params": TRIAL_16_PARAMS,
    }
    write_json(
        RESULTS_ROOT / experiment_name / "experiment_config.json",
        experiment_config,
    )

    print("=" * 80)
    print("Full-episode closing SAC with LQR-prefilled replay")
    print("=" * 80)
    print(f"Experiment:          {experiment_name}")
    print(f"Dataset:             {args.demonstrations.resolve()}")
    print(f"Demonstrations:      {demonstration_count:,} transitions")
    print(f"Successful episodes: {dataset_metadata['successful_episodes']}")
    print(f"Online timesteps:    {args.total_timesteps:,} per seed")
    print(f"Replay capacity:     {buffer_size:,}")
    print(f"Reward version:      {reward_version}")
    print(f"Training seeds:      {args.seeds}")
    print("Online resets:       ordinary full P2 distribution only")
    print("Online LQR use:      none")
    print("=" * 80)

    for seed in args.seeds:
        train_one_seed(
            args=args,
            dataset=dataset,
            dataset_metadata=dataset_metadata,
            reward_version=reward_version,
            buffer_size=buffer_size,
            checkpoint_steps=checkpoint_steps,
            experiment_name=experiment_name,
            seed=seed,
        )


if __name__ == "__main__":
    main()
