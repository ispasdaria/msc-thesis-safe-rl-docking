"""Train standalone full-episode closing SAC from LQR-prefilled replay.

This is an additive experiment entrypoint.  It does not change closing resets,
the simulator, the LQR controller, or the existing SAC training scripts.  Every
online episode uses the ordinary full P2 training distribution; LQR is used
only in the offline dataset loaded before ``model.learn()``.

Example
-------
python train_sac_closing_lqr_replay.py \
    --demonstrations demonstrations/lqr_closing_training_rewardv20_30successes.npz \
    --device cuda --progress-bar
"""

