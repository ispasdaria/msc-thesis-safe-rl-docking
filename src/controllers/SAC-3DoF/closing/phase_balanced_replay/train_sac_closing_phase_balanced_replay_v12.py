"""Train V12 vanilla SAC with online phase-balanced replay.

This is an algorithmic ablation over the strongest reward version.  It uses
only transitions generated by the current SAC agent: no LQR demonstrations,
behavior cloning, controller mixing, curriculum, or safety filter.
"""

from pathlib import Path
import sys


CURRICULUM_DIR = (
    Path(__file__).resolve().parent.parent / "curriculum_and_p3_reach"
)
SCRIPT_DIR = Path(__file__).resolve().parent
for path in (SCRIPT_DIR, CURRICULUM_DIR):
    if str(path) not in sys.path:
        sys.path.insert(0, str(path))

import train_sac_closing_p3reach_from_scratch as training

from envs.docking3dof.closing_safety_exploration_env import (
    ClosingSafetyExplorationV12GymEnv,
)
from phase_balanced_replay_buffer import PhaseBalancedReplayBuffer


CAPTURE_DISTANCE_M = 400.0
CAPTURE_BUFFER_SIZE = 100_000
PRIORITY_BUFFER_SIZE = 25_000
CAPTURE_BATCH_FRACTION = 0.50
PRIORITY_CAPTURE_FRACTION = 0.50
MINIMUM_CAPTURE_TRANSITIONS = 256


def checkpoint_rank_position_first_until_success(summary):
    """Prefer actual approach depth until the first successful capture."""
    success_rate = float(summary["success_rate"])
    second_metric = (
        -float(summary["mean_minimum_position_error_m"])
        if success_rate == 0.0
        else -float(summary["mean_final_max_target_ratio"])
    )
    return (
        success_rate,
        second_metric,
        -float(summary["mean_final_position_error_m"]),
        -float(summary["mean_final_max_target_ratio"]),
        -float(summary["mean_unsafe_fraction"]),
        float(summary["mean_return"]),
    )


training.EXPERIMENT_ENV_CLASS = ClosingSafetyExplorationV12GymEnv
training.EXPERIMENT_REWARD_SCHEME = ClosingSafetyExplorationV12GymEnv.reward_scheme
training.EXPERIMENT_REPLAY_BUFFER_CLASS = PhaseBalancedReplayBuffer
training.EXPERIMENT_REPLAY_BUFFER_KWARGS = {
    "capture_buffer_size": CAPTURE_BUFFER_SIZE,
    "priority_buffer_size": PRIORITY_BUFFER_SIZE,
    "capture_distance_m": CAPTURE_DISTANCE_M,
    "capture_batch_fraction": CAPTURE_BATCH_FRACTION,
    "priority_capture_fraction": PRIORITY_CAPTURE_FRACTION,
    "minimum_capture_transitions": MINIMUM_CAPTURE_TRANSITIONS,
}
training.EXPERIMENT_NAME_EXTRA_TAG = "phase_balanced_replay_"
training.CHECKPOINT_RANK_FUNCTION = checkpoint_rank_position_first_until_success
training.CHECKPOINT_SELECTION_ORDER = [
    "highest success rate",
    "if success is zero: lowest mean minimum P3 position error",
    "if success is nonzero: lowest mean final max target ratio",
    "lowest mean final P3 position error",
    "lowest mean final max target ratio",
    "lowest mean unsafe fraction",
    "highest mean return",
]

_build_base_config = training.build_config


def build_phase_balanced_config(args, checkpoints, experiment_name):
    config = _build_base_config(args, checkpoints, experiment_name)
    config.update(
        {
            "purpose": (
                "V12 vanilla SAC ablation with online phase-balanced replay"
            ),
            "reward_changed_from_v12": False,
            "policy_or_critic_warm_start_used": False,
            "lqr_policy_or_actions_used": False,
            "cbf_filter_used_during_training": False,
            "curriculum_used": False,
            "phase_balanced_replay": {
                "enabled": True,
                "logical_partitions": {
                    "global": "all online closing transitions",
                    "capture": (
                        "online transitions with P3 position error at or below "
                        f"{CAPTURE_DISTANCE_M:g} m"
                    ),
                },
                "batch_composition_after_activation": {
                    "global_fraction": 1.0 - CAPTURE_BATCH_FRACTION,
                    "capture_fraction": CAPTURE_BATCH_FRACTION,
                    "priority_fraction_within_capture": (
                        PRIORITY_CAPTURE_FRACTION
                    ),
                },
                "activation_after_capture_transitions": (
                    MINIMUM_CAPTURE_TRANSITIONS
                ),
                "capture_buffer_capacity": CAPTURE_BUFFER_SIZE,
                "protected_priority_capacity": PRIORITY_BUFFER_SIZE,
                "priority_events": [
                    "closest approach",
                    "velocity stopping-margin crossing",
                    "P3 axial overshoot",
                    "successful braking while approaching",
                    "P3 success",
                ],
                "fallback_before_activation": (
                    "100% ordinary global uniform replay"
                ),
                "capture_boundary_rationale": (
                    "400 m matches the existing V12 near-target gate and "
                    "allows the partition to activate for the observed "
                    "225-290 m V12 approach; 200 m remains a later ablation"
                ),
            },
        }
    )
    config["near_target_capture_shaping"]["type"] = (
        "unchanged V12 bounded balanced capture progress"
    )
    config["checkpoint_selection"] = training.CHECKPOINT_SELECTION_ORDER
    return config


training.build_config = build_phase_balanced_config


if __name__ == "__main__":
    training.main()
